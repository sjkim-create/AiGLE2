/* nar — 이 문항 · 언어의 음성 설명(lib/narration.js). 있으면 「소리가 주인, 필기가 따라간다」
 *   도입 음성 → 장면마다 설명 길이에 맞춰 필기 배속(k)을 바꿔 그린다 → 마무리 음성
 *   반환: 단계 배열 + aud(음성 구간 [{ t0(화면 시각), a0, a1(음성 파일 시각) }]) · total(전체 길이) */
const buildTimeline = (steps, pen, mode, lang = 'ko', nar = null) => {
  let t = 0;
  let gi = 0; // 문항 전체 장면 번호 — nar.segs와 1:1
  const aud = [];
  const lineCursor = {};
  if (nar?.intro) { aud.push({ t0: 0, a0: nar.intro[0], a1: nar.intro[1] }); t = nar.intro[1] - nar.intro[0] + 0.3; }
  const out = steps.map((s, i) => {
    const start = t;
    const cues = (s.cues || [{ w: s.text || '', say: s.basic }]).map((c) => {
      const seg = nar ? nar.segs[gi] : null;
      gi += 1;
      const cs = t;
      const w = c.w || '';
      const from = lineCursor[s.line] || 0;
      lineCursor[s.line] = from + w.length;
      const sched = pen && c.s ? penSchedule(pen, c.s[0], c.s[1]) : null;
      const W = cueWriteSec(c, pen);
      const txt = cueText(c, mode, lang);
      const D = seg ? seg[1] - seg[0] : 0;
      const k = fitWriting(W, D);
      let dur;
      if (D > 0) {
        aud.push({ t0: cs, a0: seg[0], a1: seg[1] });
        dur = c.pause ? Math.max(D + 0.25, PAUSE_SHOW_SEC) : Math.max(D + 0.25, W * k + 0.2);
      } else {
        const base = c.pause ? PAUSE_SHOW_SEC : W > 0 ? W + 0.3 : 0;
        dur = txt && !nar ? Math.max(base, readSec(txt)) : base;
      }
      t += dur;
      return { ...c, txt, k, start: cs, end: t, from, len: w.length, writeEnd: cs + W * k, sched };
    }).filter((c) => c.end > c.start);
    const end = t;
    if (i < steps.length - 1) t += nar ? 0.2 : GAP_SEC;
    return { ...s, start, end, cues };
  });
  if (nar?.outro) { t += 0.3; aud.push({ t0: t, a0: nar.outro[0], a1: nar.outro[1] }); t += nar.outro[1] - nar.outro[0] + 0.3; }
  out.aud = aud;
  out.total = Math.max(t, out[out.length - 1].end);
  return out;
};

const fmt = (sec) => `${Math.floor(sec / 60)}:${String(Math.floor(sec % 60)).padStart(2, '0')}`;

/* lang · onLangChange — 학생 결과 화면처럼 화면 전체 언어가 있으면 그것을 따른다(없으면 이 패널 안에서만 바꾼다) */
const SolutionReplay = ({ q, A, onClose, viewer = 'student', studentName, sampleNote, inline = false, panel = false, reportNode = null, stageTarget = null, stagePaperClass = '', stageLineClass = '', side = 'right', closing = false, lang: langProp, onLangChange, qButtonTarget = null }) => {
  const [fold, setFold] = useState(false); // inline — 오른쪽 위 풀이 과정 패널 접기(접으면 아래 채점 결과가 올라온다)
  const isTeacher = viewer === 'teacher';
  const sol = q.solution;
  const pen = sol.pen || null;
  const [len, setLen] = useState('basic'); // basic(간단히) · detail(자세히) — 자막 · 정리 함께
  const [lang, setLang] = useState(langProp || 'ko'); // [다국어] lib/i18n — 지금은 ko · en
  const U = uiOf(UI, lang);
  const noLang = !hasLang(sol, lang); // 이 문항은 선택한 언어의 설명 데이터가 없다
  const [asking, setAsking] = useState(false); // [모르겠어요] 풀이 전체 다시 정리 열림
  const [qOpen, setQOpen] = useState(false); // [문항 보기] 문항 글은 버튼 → 모달(긴 문항이 패널을 차지하지 않게)
  /* [음성 설명 · 시연용] 교사가 옆에서 설명하듯 — 자막(정리)과 따로인 원고. 기본은 꺼짐(교실에서 여럿이 열면 시끄럽다) · 음성이 있는 문항만 버튼이 보인다 */
  const [narAll, setNarAll] = useState(null);
  const [voiceOn, setVoiceOn] = useState(false);
  useEffect(() => { loadNarration().then(setNarAll); }, []);
  const narOf = (lg) => narrationOf(narAll, q.text, lg);
  const voiceReady = !!narOf(lang);
  const voice = useMemo(() => (voiceOn ? narrationOf(narAll, q.text, lang) : null), [voiceOn, narAll, q.text, lang]);
  const tl = useMemo(() => buildTimeline(sol.steps, pen, len, lang, voice), [sol, pen, len, lang, voice]);
  const penVB = useMemo(() => (pen ? penViewBox(pen, sol.penFrom || 0) : null), [pen, sol.penFrom]);
  const total = tl.total;
  const [t, setT] = useState(0);
  const [playing, setPlaying] = useState(true);
  const [speed, setSpeed] = useState(1);
  const raf = useRef(0);
  const last = useRef(0);

  useEffect(() => {
    if (!playing) return undefined;
    last.current = performance.now();
    const tick = (now) => {
      const dt = ((now - last.current) / 1000) * speed;
      last.current = now;
      setT((v) => {
        const nv = Math.min(total, v + dt);
        if (nv >= total) setPlaying(false);
        return nv;
      });
      raf.current = requestAnimationFrame(tick);
    };
    raf.current = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf.current);
  }, [playing, speed, total]);

  useEffect(() => {
    const onKey = (e) => {
      if (e.key === 'Escape') { if (qOpen) setQOpen(false); else onClose(); return; }
      if (qOpen) return;
      if (e.key === ' ') { e.preventDefault(); toggle(); }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  });

  const cur = Math.max(0, tl.findIndex((s, i) => t < (tl[i + 1]?.start ?? Infinity)));
  const step = tl[cur];
  const cue = step.cues.find((c) => t >= c.start && t < c.end) || (t >= step.end ? step.cues[step.cues.length - 1] : null);
  const pausing = !!(cue?.pause && t < cue.end);

  const toggle = () => {
    if (t >= total) { setT(0); setPlaying(true); return; }
    setPlaying((p) => !p);
  };
  const seek = (v) => setT(v);
  /* 간단히 ↔ 자세히 — 시간표가 바뀌므로 지금 단계의 처음으로 맞춘다 */
  const changeLen = (v) => {
    if (v === len) return;
    const nt = buildTimeline(sol.steps, pen, v, lang, voice);
    setLen(v);
    setT(t >= total ? nt.total : nt[cur].start);
  };
  /* 언어 — 자막 길이가 달라 시간표가 바뀌므로 지금 단계의 처음으로 */
  const changeLang = (v) => {
    if (v === lang) return;
    const nt = buildTimeline(sol.steps, pen, len, v, voiceOn ? narOf(v) : null);
    setLang(v);
    setT(t >= total ? nt.total : nt[cur].start);
    if (v !== langProp) onLangChange?.(v);
  };
  /* 화면 전체 언어가 바뀌면 따라간다 */
  useEffect(() => { if (langProp && langProp !== lang) changeLang(langProp); }, [langProp]); // eslint-disable-line react-hooks/exhaustive-deps
  /* [모르겠어요] 열면 재생을 멈추고 다시 정리에 집중한다 */
  const openAsk = () => { setPlaying(false); setAsking(true); };
  const goStep = (i) => { setT(tl[i].start); setPlaying(true); };

  /* 음성 켜기 · 끄기 — 시간표가 바뀌므로 지금 단계의 처음으로(맨 처음이면 도입부터) */
  const toggleVoice = () => {
    const on = !voiceOn;
    const nt = buildTimeline(sol.steps, pen, len, lang, on ? narOf(lang) : null);
    setVoiceOn(on);
    setT(t >= total ? nt.total : t < tl[0].start || cur === 0 ? 0 : nt[cur].start);
    if (on) setPlaying(true);
  };
  /* 음성 파일 하나를 재생 위치에 맞춰 튼다 — 장면 설명 구간에서만 소리, 그 밖(필기가 더 긴 부분)은 쉼.
   *   일시정지 · 구간 이동 · 재생 속도를 따라간다 */
  const audio = useRef(null);
  useEffect(() => {
    const a = audio.current || (audio.current = new Audio());
    const seg = voice && playing ? tl.aud.find((g) => t >= g.t0 && t < g.t0 + (g.a1 - g.a0)) : null;
    if (!seg) { if (!a.paused) a.pause(); return; }
    if (a.dataset.src !== voice.url) { a.src = voice.url; a.dataset.src = voice.url; }
    a.playbackRate = speed;
    const want = seg.a0 + (t - seg.t0);
    if (Math.abs(a.currentTime - want) > 0.3) a.currentTime = want;
    if (a.paused) a.play().catch(() => {});
  }, [t, tl, voice, playing, speed]);
  useEffect(() => () => audio.current?.pause(), []);

  /* 펜 — 획마다 지금까지 그린 점 수 · 색(지금 단계 파랑 · 다시 볼 부분 빨강) */
  const penState = useMemo(() => {
    if (!pen) return null;
    const m = new Map();
    let tip = null;
    tl.forEach((s, si) => s.cues.forEach((c) => {
      if (!c.sched) return;
      c.sched.list.forEach(({ k, at, cum }) => {
        const lt = (t - c.start) / c.k - at; // k = 설명에 맞춘 필기 배율
        if (lt < 0) return;
        let n = cum.length;
        if (lt < cum[cum.length - 1]) { n = cum.findIndex((x) => x > lt); if (n < 1) n = 1; const pt = pen.strokes[k].p[n - 1]; tip = [pt[0], pt[1]]; }
        const color = c.mark && t >= c.end ? '#DC2626' : si === cur ? '#1D4ED8' : '#1E293B';
        m.set(k, { n, color });
      });
    }));
    return { m, tip };
  }, [pen, tl, t, cur]);

  /* 줄마다 지금까지 쓴 글자 — 장면(자막) 단위 조각 */
  const lines = q.answer.map((line, li) => tl.flatMap((s, idx) => (s.line !== li ? [] : s.cues.filter((c) => c.len > 0).map((c, k) => {
    const shown = t <= c.start ? 0 : Math.min(c.len, Math.ceil((t - c.start) / (CHAR_SEC * c.k)));
    return { key: `${idx}-${k}`, s, idx, text: line.slice(c.from, c.from + c.len), shown, writing: t > c.start && t < c.writeEnd };
  }))));

  /* [문항 보기] 버튼 — 누르면 재생을 멈추고 문항 전체를 모달로 */
  const qBtn = (
    <button type="button" className="srp-qbtn" aria-haspopup="dialog" onClick={() => { setPlaying(false); setQOpen(true); }}>
      {qButtonTarget ? `📄 ${U.viewQ}` : <><span className="srp-qtext-k">{tr(q, 'label', lang)}</span>{U.viewQ}</>}
    </button>
  );

  /* 필기 재생(장면 자막 포함) — panel이면 stageTarget(왼쪽 답안 원본 자리)에 그린다 */
  const paperNode = (
            <div className={`srp-paper ${pen ? 'pen' : ''}`} aria-label="내 필기 재생">
              <div className="srp-paper-cap">{isTeacher ? U.stuPen : U.myPen} · {tr(A, 'cap', lang)}</div>
              {pen && (
                <div className="srp-pen">
                  <PenStrokes pen={pen} from={sol.penFrom || 0} viewBox={penVB} strokeState={(k) => penState.m.get(k)} tip={penState.tip} label={isTeacher ? U.stuPen : U.myPen} />
                </div>
              )}
              {!pen && lines.map((parts, li) => (
                <div key={li} className="srp-line">
                  {parts.map(({ key, s, idx, text, shown, writing }) => (
                    <span key={key} className={`srp-seg ${idx === cur ? 'on' : ''} ${!s.ok && t >= s.end ? 'warn' : ''}`}>
                      {text.slice(0, shown)}
                      {writing && <span className="srp-tip" aria-hidden="true" />}
                      <span className="srp-ghost">{text.slice(shown)}</span>
                    </span>
                  ))}
                </div>
              ))}
              {pausing && <div className="srp-pause">{U.paused(cue.sec || step.pauseSec)}</div>}
              {/* 장면 자막 — 쓰는 순서에 맞춰 말하듯이 */}
              <div className="srp-cc" aria-live="polite">{cue?.txt && <span key={`${cur}-${cue.start}`} className={`srp-cc-t ${step.ok ? '' : 'warn'}`}>{cue.txt}</span>}</div>
            </div>
  );

  /* 재생 막대 — 필기 재생과 함께 다닌다(stageTarget이면 왼쪽 원본 아래) */
  const ctrlNode = (
            <div className="srp-ctrl">
              <button type="button" className="srp-btn main" aria-label={playing ? U.pause : U.play} onClick={toggle}>{playing ? '⏸' : t >= total ? '⟲' : '▶'}</button>
              <button type="button" className="srp-btn" aria-label={U.restart} onClick={() => { setT(0); setPlaying(true); }}>⟲</button>
              {voiceReady && <button type="button" className={`srp-btn ${voiceOn ? 'on' : ''}`} aria-pressed={voiceOn} aria-label={voiceOn ? U.voiceOff : U.voiceOn} title={`${voiceOn ? U.voiceOff : U.voiceOn} · ${U.voiceDemo}`} onClick={toggleVoice}>{voiceOn ? '🔊' : '🔇'}</button>}
              <input className="srp-seek" type="range" min={0} max={total} step={0.01} value={t} aria-label={U.seek}
                onChange={(e) => seek(Number(e.target.value))} />
              <span className="srp-time">{cur + 1}/{tl.length} · {fmt(t)}</span>
              <div className="srp-seg-btns" role="group" aria-label={U.speed}>
                {SPEEDS.map((v) => <button key={v} type="button" aria-pressed={speed === v} onClick={() => setSpeed(v)}>{v.toFixed(1)}x</button>)}
              </div>
            </div>
  );

  /* [TSK-10 v1.17] stageTarget — 답안 미리보기의 원본 화면을 그대로 쓴다(같은 상자 · 같은 크기 · 같은 글씨).
   *   원본 전체를 옅게 깔고 그 위에 쓰는 순서대로 덧그린다. 장면 자막은 원본을 가리지 않게 아래로 */
  const stageNode = (
    <>
      <div className={`${stagePaperClass} srp-stage-paper`} aria-label={isTeacher ? U.stuPen : U.myPen}>
        {pen
          ? <PenStrokes pen={pen} from={sol.penFrom || 0} viewBox={penVB} strokeState={(k) => penState.m.get(k)} tip={penState.tip} ghost="#E5E9F0" label={isTeacher ? U.stuPen : U.myPen} style={{ maxHeight: 420 }} />
          : lines.map((parts, li) => (
            <div key={li} className={`${stageLineClass} srp-stage-line`}>
              {parts.map(({ key, s, idx, text, shown, writing }) => (
                <span key={key} className={`srp-seg ${idx === cur ? 'on' : ''} ${!s.ok && t >= s.end ? 'warn' : ''}`}>
                  {text.slice(0, shown)}
                  {writing && <span className="srp-tip" aria-hidden="true" />}
                  <span className="srp-ghost">{text.slice(shown)}</span>
                </span>
              ))}
            </div>
          ))}
        {pausing && <div className="srp-pause">{U.paused(cue.sec || step.pauseSec)}</div>}
      </div>
      <div className="srp-cc-out" aria-live="polite">{cue?.txt && <span key={`${cur}-${cue.start}`} className={`srp-cc-t ${step.ok ? '' : 'warn'}`}>{cue.txt}</span>}</div>
      {ctrlNode}
    </>
  );

  return (
    <div className={inline ? 'srp-inline' : panel ? `srp-panel side-${side} ${closing ? 'closing' : ''}` : 'srp-wrap'} role={inline || panel ? 'region' : 'dialog'} aria-modal={inline || panel ? undefined : 'true'} aria-label={`${U.title} · ${tr(q, 'label', lang)}`} lang={lang}>
      <style>{CSS}</style>
      <div className="srp-box">
        <div className="srp-head">
          <div className="srp-head-l">
            {inline && <button type="button" className="srp-backbtn" onClick={onClose}>‹ {U.back}</button>}
            <div className="srp-ttl">{U.title} <span className="srp-q">{tr(q, 'label', lang)}</span></div>
            {/* 교사 확인 · 학생 이름 · 과목 · 단원 칩은 두지 않는다(화면 머리에 이미 있다) — 시연 표시 · 설명 수준만 */}
            <div className="srp-tags">
              {sampleNote && <span className="srp-tag-s">{sampleNote}</span>}
              <span title={U.levelTip}>{U.level(tr(sol, 'level', lang))}</span>
            </div>
          </div>
          <div className="srp-head-r">
            {/* [다국어 프로토] 언어 선택 — 오른쪽 위 */}
            <label className="srp-lang" title={U.lang}>
              <span aria-hidden="true">🌐</span>
              <select value={lang} aria-label={U.lang} onChange={(e) => changeLang(e.target.value)}>
                {ACTIVE_LANGS.map((l) => <option key={l.code} value={l.code}>{l.label}</option>)}
              </select>
            </label>
            {!inline && <button type="button" className="srp-x" aria-label={U.close} onClick={onClose}>✕</button>}
          </div>
        </div>

        <div className="srp-cols">
          {/* 좌: 문항 지문 + 내 필기 재생(장면 자막) + 재생 막대 — 정리는 오른쪽 풀이 단계 안 */}
          <div className={`srp-l ${!noLang && qButtonTarget && stageTarget ? 'empty' : ''}`}>{/* 문항 보기 · 필기 재생이 모두 바깥 자리로 가면 이 칸은 비어 숨긴다 */}
            {noLang && <div className="srp-noen">{U.noLang}</div>}
            {/* qButtonTarget — 화면의 문항 탭 줄(문항 탭 이름 옆)에 버튼을 둔다. 없으면 이 자리 */}
            {qButtonTarget ? createPortal(qBtn, qButtonTarget) : qBtn}
            {qOpen && createPortal(
              <div className="srp-qmodal" role="presentation" onClick={() => setQOpen(false)}>
                <div className="srp-qmodal-in" role="dialog" aria-modal="true" aria-label={`${tr(q, 'label', lang)} ${U.viewQ}`} lang={lang} onClick={(e) => e.stopPropagation()}>
                  <div className="srp-qmodal-h">
                    <b><span className="srp-qtext-k">{tr(q, 'label', lang)}</span>{U.viewQ}</b>
                    <button type="button" className="srp-x" aria-label={U.close} onClick={() => setQOpen(false)} autoFocus>✕</button>
                  </div>
                  <div className="srp-qtext">{tr(q, 'text', lang)}</div>
                </div>
              </div>, document.body)}
            {stageTarget ? createPortal(stageNode, stageTarget) : paperNode}

            {!stageTarget && ctrlNode}
          </div>

          {/* 우: 단계 목록 · 설명 길이 · 정답 */}
          <div className="srp-r">
            {/* inline — 풀이 과정 패널(접기) · 접으면 지금 단계만 한 줄 */}
            {inline && (
              <button type="button" className="srp-fold-h" aria-expanded={!fold} onClick={() => setFold((v) => !v)}>
                <b>{U.tabSteps}</b>
                <span className="srp-fold-cur">{String(cur + 1).padStart(2, '0')} {tr(step, 'title', lang)}<span className={`srp-dot ${step.ok ? 'ok' : 'no'}`}>{step.ok ? '✓' : '!'}</span></span>
                <span className="srp-chev" aria-hidden="true">{fold ? '▾' : '▴'}</span>
              </button>
            )}
            {(!inline || !fold) && (<>
            <div className="srp-rhead">
              <b>{U.steps}</b>
              <div className="srp-seg-btns" role="group" aria-label={U.lenTip} title={U.lenTip}>
                <button type="button" aria-pressed={len === 'basic'} onClick={() => changeLen('basic')}>{U.short}</button>
                <button type="button" aria-pressed={len === 'detail'} onClick={() => changeLen('detail')}>{U.long}</button>
              </div>
            </div>
            <ol className="srp-steps">
              {tl.map((s, i) => (
                <li key={i} className={`srp-li ${i === cur ? 'open' : ''} ${s.ok ? '' : 'warn'}`}>
                  <button type="button" className={`srp-step ${i === cur ? 'on' : ''} ${t >= s.end ? 'done' : ''}`} aria-expanded={i === cur} onClick={() => goStep(i)}>
                    <span className="srp-no">{String(i + 1).padStart(2, '0')}</span>
                    <span className="srp-step-t">{tr(s, 'title', lang)}</span>
                    <span className={`srp-dot ${s.ok ? 'ok' : 'no'}`} aria-label={s.ok ? U.good : U.again}>{s.ok ? '✓' : '!'}</span>
                  </button>
                  {/* 정리 — 지금 단계가 펼쳐질 때만 */}
                  {i === cur && (
                    <div className="srp-sum">
                      <div className="srp-sum-k">{U.summary}<span className={`srp-mark ${s.ok ? 'ok' : 'no'}`}>{s.ok ? U.good : U.again}</span></div>
                      <div className="srp-sum-d">{tr(s, len === 'detail' ? 'detail' : 'basic', lang)}</div>
                    </div>
                  )}
                </li>
              ))}
            </ol>

            {/* [모르겠어요] 학생만 · 단계마다가 아니라 풀이 전체에 하나 — AI가 모든 단계를 묶어 처음부터 다시 정리한다 */}
            {!isTeacher && (
              <div className="srp-ask">
                {asking
                  ? <DontGetIt lang={lang} level={tr(sol, 'level', lang)} onClose={() => setAsking(false)}
                      ctx={{ subject: tr(A, 'subject', lang), question: tr(q, 'text', lang), answer: q.answer, correct: tr(sol, 'answer', lang),
                        explained: sol.steps.map((s, i) => `${i + 1}. ${tr(s, 'title', lang)} (${s.ok ? 'OK' : 'needs fixing'}): ${tr(s, 'detail', lang) || tr(s, 'basic', lang)}`) }} />
                  : <DontGetIt.Button lang={lang} onClick={openAsk} />}
              </div>
            )}

            <div className="srp-concept">
              <div className="k">{U.concept}</div>
              <div>{tr(sol, 'concept', lang)}</div>
            </div>

            {/* 바른 풀이 — 처음부터 열려 있다(잠금 없음) */}
            <div className="srp-answer open">
              <div className="k">{U.answer}</div>
              {tr(sol, 'answer', lang).map((l, i) => <div key={i} className="srp-ans-l">{l}</div>)}
            </div>
            </>)}
            {inline && (
              <div className="srp-rep-wrap">
                <div className="srp-rep-t">{U.tabReport}</div>
                <div className="srp-report">{reportNode}</div>
              </div>
            )}
          </div>
        </div>

        {/* 교사 확인용 안내는 교사 화면(GradingReviewModal) 오른쪽 「문항 n 원본 보기」 제목 옆에 둔다 */}
        {!isTeacher && <div className="srp-foot">{U.footS}</div>}
      </div>
    </div>
  );
};

